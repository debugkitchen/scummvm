#ifndef TAD_SCRIPT_H
#define TAD_SCRIPT_H

#include "common/hashmap.h"
#include "common/str.h"

#include "tad/dosvm.h"

namespace Tad {

class ScriptRuntime;
class ProgramVm;

/** A function of the game translated from the original program (generated by tools/adcpp.py) */
typedef void (*ScriptFunctionPtr)(ScriptRuntime &s);
struct ScriptFunction {
	uint16 seg;
	uint16 off;
	ScriptFunctionPtr fn;
};

/** AX and DX after a call */
struct CallResult {
	uint16 ax = 0;
	uint16 dx = 0;
};

/** Registers at the entry of a translated function */
struct EntryRegs {
	uint16 ax, bx, cx, dx, si, di, es, bp;
};

/** Stack frame of a translated function, laid out as the original one */
struct ScriptFrame {
	uint16 sp0 = 0;      ///< SP at the entry (return address)
	uint16 bp = 0;       ///< frame pointer
	uint16 ab = 0;       ///< address of the first argument
	uint16 ss = 0;
	uint16 si = 0;       ///< SI and DI of the caller (restored on return)
	uint16 di = 0;
	uint16 seg = 0;
	bool bpFrame = true;
	bool nearFunc = false;
	uint32 steps = 0;    ///< blocks run (a loop that never ends lets the frame end)
	EntryRegs entry;
};

/** Turbo C long arithmetic helpers (LXMUL@, LDIV@ ...) */
enum LongOp { kLongMul, kLongDiv, kLongMod, kLongUDiv, kLongUMod, kLongShl, kLongSar, kLongShr };
CallResult longOp(LongOp op, const uint16 *a);

static inline int32 sx16(uint32 v) { return (int16)(uint16)v; }
static inline int32 sx8(uint32 v) { return (int8)(byte)v; }
static inline uint16 sdiv(uint16 a, uint16 b) { const int32 d = sx16(b); return d ? (uint16)(sx16(a) / d) : 0; }
static inline uint16 smod(uint16 a, uint16 b) { const int32 d = sx16(b); return d ? (uint16)(sx16(a) % d) : 0; }

/**
 * Runs the translated functions inside the emulated program: each one sets up the stack frame
 * of the original, so translated, and original code can call each other.
 */
class ScriptRuntime {
public:
	ScriptRuntime(ProgramVm *program, DosVm *machine, uint16 dataSeg) : prog(program), vm(machine), ds(dataSeg),
		blocks(0), _failed(false) {}

	/** Registers the functions of a table (a trap at each address) */
	void install(const ScriptFunction *list);
	bool has(uint16 seg, uint16 off) const { return _funcs.contains(((uint32)seg << 16) | off); }
	/** Runs the translated function at seg:off; the return address is on the stack */
	void invoke(uint16 seg, uint16 off);
	uint count() const { return _funcs.size(); }

	byte rb(uint16 seg, uint16 off) const { return vm->rb(seg, off); }
	uint16 rw(uint16 seg, uint16 off) const { return vm->rw(seg, off); }
	void wb(uint16 seg, uint16 off, uint v) { vm->wb(seg, off, v); }
	void ww(uint16 seg, uint16 off, uint v) { vm->ww(seg, off, v); }

	/** Prologue of a translated function as in the original (push bp, mov bp,sp, sub sp, push si/di) */
	void enter(ScriptFrame &fr, bool bpFrame, uint16 frameSize, bool nearFunc, uint16 seg, const char *saves);
	/** Epilogue: the far (or near) return with AX = ret, DX = retd */
	void leave(ScriptFrame &fr, uint16 ret, uint16 retd);
	/** SI and DI hold the caller's register variables during a call (Turbo C) */
	void setRegVars(uint16 si, uint16 di) {
		vm->r16[kSI] = si;
		vm->r16[kDI] = di;
	}
	/** Call of a function (translated or original code); the frame may end inside */
	CallResult call(uint16 seg, uint16 off, bool nearCall, const uint16 *args, uint n);
	/** Turbo C huge pointer arithmetic: the far pointer at a[1]:a[0] plus or minus a[3]:a[2] */
	CallResult hugeOp(bool add, const uint16 *a);
	/** Start of a block; true when the program is being stopped (the function returns at once) */
	bool blockStep(ScriptFrame &fr);
	void fail(const char *msg);

	ProgramVm *prog;
	DosVm *vm;
	const uint16 ds;
	uint32 blocks;          ///< blocks run in all translated functions

private:
	Common::HashMap<uint32, ScriptFunctionPtr> _funcs;
	bool _failed;
};

} // End of namespace Tad

#endif // TAD_SCRIPT_H
